-- 005_agent_calls_instance.sql
-- Добавляет колонку экземпляра службы в журнал вызовов: имя машины и порт
-- (или явное значение из [server] instance). Нужна, чтобы при старте служба
-- закрывала ошибкой ТОЛЬКО свои повисшие running-строки: без колонки две
-- службы на одной базе гасили вызовы друг друга. Идемпотентно; старые сборки
-- пишут NULL — такие строки не трогаются.
ALTER TABLE agents_mcp.agent_calls
    ADD COLUMN IF NOT EXISTS instance text;
